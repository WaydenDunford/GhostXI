// Shared momentum generator: base wave + moment impacts, ghost branch after ghostFrom.
function series(moments: Moment[], max: number, ghostFrom: number, ghostBoost = 22) {
  return Array.from({ length: max / 2 + 1 }, (_, i) => {
    const minute = i * 2;
    const base = Math.sin(minute / 9) * 30 + Math.cos(minute / 4) * 12;
    const m = moments.find((x) => Math.abs(x.minute - minute) <= 1);
    const v = Math.max(-80, Math.min(80, Math.round(base + (m ? m.impact : 0))));
    const ghost =
      minute >= ghostFrom ? Math.min(80, v + ghostBoost + Math.round(Math.sin(minute) * 4)) : v;
    return { minute, momentum: v, ghost };
  });
}

